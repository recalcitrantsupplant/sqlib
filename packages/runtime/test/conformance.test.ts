/**
 * Golden cases shared with the .NET runtime in `dotnet/`.
 *
 * This test runs every case in `conformance/cases.ts` through this runtime and
 * compares the outcomes with `conformance/goldens.json`. The .NET suite reads
 * the same file. A change here that alters an outcome fails this test until
 * the file is rewritten, and the rewrite then fails the .NET suite until the
 * port follows.
 *
 * Rewrite the file with:
 *
 *     SQLIB_UPDATE_GOLDENS=1 pnpm --filter @sparql-query-lib/runtime exec vitest run test/conformance.test.ts
 */

import { describe, expect, it } from 'vitest';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { assertValidBundle, verifyBundleIntegrity, type ExportBundle } from '../src/bundle.js';
import { compileValuePattern } from '../src/query-template.js';
import { fromBundle } from '../src/library.js';
import { buildCases, type BundleSource } from './conformance/cases.js';

const HERE = import.meta.dirname;
const FIXTURES = resolve(HERE, 'fixtures');
const GOLDENS = resolve(HERE, 'conformance', 'goldens.json');
const FIXTURE_NAMES = ['bundle-v1.json', 'bundle-v2.json', 'bundle-v1-minimal.json'];

type Outcome =
  | { ok: true }
  | { text: string }
  | { matches: boolean }
  | { error: { type: string; message?: string; messagePrefix?: string } };

/** The text up to the reason a JavaScript engine gives for a bad pattern. */
const ENGINE_REASON = /^(.*is not a valid regular expression: )/s;

function errorOutcome(error: unknown): Outcome {
  const { name, message } = error as Error;
  const engine = ENGINE_REASON.exec(message);
  return engine ? { error: { type: name, messagePrefix: engine[1] } } : { error: { type: name, message } };
}

function sourceText(source: BundleSource): string {
  return 'fixture' in source ? readFileSync(resolve(FIXTURES, source.fixture), 'utf8') : source.json;
}

async function loadBundle(json: string) {
  const bundle = JSON.parse(json) as ExportBundle;
  assertValidBundle(bundle);
  await verifyBundleIntegrity(bundle);
  return fromBundle(bundle, { validate: false });
}

async function computeGoldens() {
  const fixtures = Object.fromEntries(
    FIXTURE_NAMES.map((name) => [name, JSON.parse(readFileSync(resolve(FIXTURES, name), 'utf8')) as ExportBundle]),
  );
  const inputs = await buildCases(fixtures);

  const load = [];
  for (const entry of inputs.load) {
    let expect: Outcome;
    try {
      await loadBundle(sourceText(inputs.bundles[entry.bundle]));
      expect = { ok: true };
    } catch (error) {
      expect = errorOutcome(error);
    }
    load.push({ ...entry, expect });
  }

  const calls = [];
  for (const entry of inputs.calls) {
    const library = await loadBundle(sourceText(inputs.bundles[entry.bundle]));
    let expect: Outcome;
    try {
      expect = { text: library.query(entry.query).text(JSON.parse(entry.payload)) };
    } catch (error) {
      expect = errorOutcome(error);
    }
    calls.push({ ...entry, expect });
  }

  const valuePatterns = inputs.valuePatterns.map((entry) => {
    let expect: Outcome;
    try {
      expect = { matches: compileValuePattern(entry.pattern).test(entry.value) };
    } catch (error) {
      expect = errorOutcome(error);
    }
    return { ...entry, expect };
  });

  return {
    about:
      'Generated by packages/runtime/test/conformance.test.ts from conformance/cases.ts. Do not edit by hand. Read by dotnet/test.',
    format: 1,
    bundles: inputs.bundles,
    load,
    calls,
    valuePatterns,
  };
}

describe('cross-runtime golden cases', () => {
  it('match conformance/goldens.json', async () => {
    const actual = `${JSON.stringify(await computeGoldens(), null, 2)}\n`;
    if (process.env.SQLIB_UPDATE_GOLDENS === '1') {
      writeFileSync(GOLDENS, actual);
      return;
    }
    let committed = '';
    try {
      committed = readFileSync(GOLDENS, 'utf8');
    } catch {
      // A missing file fails the comparison below.
    }
    expect(
      actual === committed,
      'conformance/goldens.json differs from this runtime. Rerun with SQLIB_UPDATE_GOLDENS=1, review the diff, and update dotnet/ to match.',
    ).toBe(true);
  });
});
