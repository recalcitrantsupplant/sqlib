/**
 * The Litestream configuration for the SQLite files this sqlib uses.
 *
 * Which files exist, and where, is decided by the same functions the server
 * calls (`getInternalBackendConfig`, `buildAuthConfig`), so the replicator
 * always watches the files the server writes.
 *
 * No credential is ever written into the file. Litestream reads credentials
 * from its environment; a SAS token is referenced as `${...}` and expanded by
 * Litestream at load time.
 */
import path from 'node:path';
import { buildAuthConfig } from '../auth/config.js';
import { getInternalBackendConfig } from '../server/config.js';
import { replicaUrlFor, type ReplicaSettings } from './settings.js';

/*
 * The stores' file names. Not imported from the stores themselves, because
 * those modules load Oxigraph, and the supervisor that uses this file should
 * stay small. A test checks that they match.
 */
export const LIBRARY_SQLITE_FILE = 'library.sqlite';
export const AUTH_SQLITE_FILE = 'auth.sqlite';

export type DatabaseName = 'library' | 'auth';

export interface ReplicatedDatabase {
  name: DatabaseName;
  /** Absolute path of the SQLite file. */
  path: string;
}

/** Every SQLite file the server will open with this environment. */
export function listDatabases(env: NodeJS.ProcessEnv = process.env): ReplicatedDatabase[] {
  const databases: ReplicatedDatabase[] = [];

  const library = getInternalBackendConfig(env);
  if (library.type === 'sqlite' && library.storageDir !== ':memory:') {
    databases.push({ name: 'library', path: path.join(library.storageDir, LIBRARY_SQLITE_FILE) });
  }

  const auth = buildAuthConfig(env);
  if (auth.mode !== 'disabled' && auth.store.type === 'sqlite') {
    databases.push({ name: 'auth', path: path.join(auth.store.dir, AUTH_SQLITE_FILE) });
  }

  return databases;
}

/**
 * A YAML scalar. JSON strings are valid YAML double-quoted scalars. A `$` is
 * refused, because Litestream expands `$VAR` in its config.
 */
function scalar(value: string): string {
  if (value.includes('$')) {
    throw new Error(`A replication setting contains "$", which Litestream would expand as a variable: ${JSON.stringify(value)}`);
  }
  return JSON.stringify(value);
}

export function buildLitestreamConfig(databases: readonly ReplicatedDatabase[], settings: ReplicaSettings): string {
  const { location } = settings;
  if (!location) {
    throw new Error('buildLitestreamConfig needs SQLIB_SQLITE_REPLICA_URL.');
  }
  if (databases.length === 0) {
    throw new Error(
      'SQLIB_SQLITE_REPLICA_URL is set, but this configuration uses no SQLite file: ' +
        'the library is not INTERNAL_BACKEND_TYPE=sqlite on disk, and auth is disabled or not SQLIB_AUTH_STORE_TYPE=sqlite. ' +
        'Unset SQLIB_SQLITE_REPLICA_URL, or use a SQLite store.'
    );
  }

  const lines = [
    '# Generated by sqlib at start (packages/api/src/replication/litestreamConfig.ts).',
    `shutdown-sync-timeout: ${settings.shutdownSyncTimeout}`,
  ];
  if (settings.metricsAddr) lines.push(`addr: ${scalar(settings.metricsAddr)}`);
  lines.push(
    'snapshot:',
    `  interval: ${settings.snapshotInterval}`,
    `  retention: ${settings.retention}`,
    'dbs:'
  );

  for (const database of databases) {
    lines.push(
      `  - path: ${scalar(database.path)}`,
      '    replica:',
      `      url: ${scalar(replicaUrlFor(location, database.name))}`
    );
    if (settings.endpoint) lines.push(`      endpoint: ${scalar(settings.endpoint)}`);
    if (settings.region) lines.push(`      region: ${scalar(settings.region)}`);
    lines.push(`      sync-interval: ${settings.syncInterval}`);
    if (settings.kmsKeyId) lines.push(`      sse-kms-key-id: ${scalar(settings.kmsKeyId)}`);
    // Expanded by Litestream from its environment, so the token stays out of the file.
    if (settings.azureSas) lines.push('      sas-token: "${SQLIB_SQLITE_REPLICA_AZURE_SAS}"');
  }

  return `${lines.join('\n')}\n`;
}
