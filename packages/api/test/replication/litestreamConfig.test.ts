import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { AUTH_SQLITE_FILE as AUTH_STORE_FILE } from '../../src/auth/sqlitePersistence.js';
import { LIBRARY_SQLITE_FILE as LIBRARY_STORE_FILE } from '../../src/persistence/sqliteEntityStore.js';
import { AUTH_SQLITE_FILE, buildLitestreamConfig, LIBRARY_SQLITE_FILE, listDatabases } from '../../src/replication/litestreamConfig.js';
import { readReplicaSettings } from '../../src/replication/settings.js';

const anonymous = { SQLIB_AUTH_MODE: 'anonymous' };

describe('listDatabases', () => {
  it('names the same files the stores open', () => {
    expect(LIBRARY_SQLITE_FILE).toBe(LIBRARY_STORE_FILE);
    expect(AUTH_SQLITE_FILE).toBe(AUTH_STORE_FILE);
  });

  it('lists the library alone by default, since auth is disabled by default', () => {
    expect(listDatabases({})).toEqual([
      { name: 'library', path: path.resolve('./storage/library-store/library.sqlite') },
    ]);
  });

  it('adds the auth file when auth is on with the sqlite store', () => {
    expect(listDatabases({ ...anonymous, LIBRARY_STORAGE_DIR: '/data/lib', SQLIB_AUTH_STORE_DIR: '/data/auth' })).toEqual([
      { name: 'library', path: '/data/lib/library.sqlite' },
      { name: 'auth', path: '/data/auth/auth.sqlite' },
    ]);
  });

  it('leaves out stores that are not SQLite files', () => {
    expect(listDatabases({ ...anonymous, INTERNAL_BACKEND_TYPE: 'http', SQLIB_AUTH_STORE_DIR: '/a' })).toEqual([
      { name: 'auth', path: '/a/auth.sqlite' },
    ]);
    expect(listDatabases({ LIBRARY_STORAGE_DIR: ':memory:' })).toEqual([]);
    expect(listDatabases({ ...anonymous, SQLIB_AUTH_STORE_TYPE: 'file' })).toHaveLength(1);
    expect(listDatabases({ INTERNAL_BACKEND_TYPE: 'oxigraph-persistent' })).toEqual([]);
  });
});

describe('buildLitestreamConfig', () => {
  const databases = [
    { name: 'library' as const, path: '/data/lib/library.sqlite' },
    { name: 'auth' as const, path: '/data/auth/auth.sqlite' },
  ];

  it('writes one replica per database under the base URL', () => {
    const yaml = buildLitestreamConfig(databases, readReplicaSettings({ SQLIB_SQLITE_REPLICA_URL: 's3://bucket/prod' })!);
    expect(yaml).toBe(
      [
        '# Generated by sqlib at start (packages/api/src/replication/litestreamConfig.ts).',
        'shutdown-sync-timeout: 10s',
        'snapshot:',
        '  interval: 6h',
        '  retention: 72h',
        'dbs:',
        '  - path: "/data/lib/library.sqlite"',
        '    replica:',
        '      url: "s3://bucket/prod/library"',
        '      sync-interval: 1s',
        '  - path: "/data/auth/auth.sqlite"',
        '    replica:',
        '      url: "s3://bucket/prod/auth"',
        '      sync-interval: 1s',
        '',
      ].join('\n')
    );
  });

  it('adds the endpoint, region, KMS key and metrics address when set', () => {
    const yaml = buildLitestreamConfig(
      databases.slice(0, 1),
      readReplicaSettings({
        SQLIB_SQLITE_REPLICA_URL: 's3://bucket/prod',
        SQLIB_SQLITE_REPLICA_ENDPOINT: 'https://acct.r2.cloudflarestorage.com',
        SQLIB_SQLITE_REPLICA_REGION: 'auto',
        SQLIB_SQLITE_REPLICA_KMS_KEY_ID: 'arn:aws:kms:eu-west-1:1:key/abc',
        SQLIB_SQLITE_REPLICA_METRICS_ADDR: ':9090',
      })!
    );
    expect(yaml).toContain('addr: ":9090"');
    expect(yaml).toContain('      endpoint: "https://acct.r2.cloudflarestorage.com"');
    expect(yaml).toContain('      region: "auto"');
    expect(yaml).toContain('      sse-kms-key-id: "arn:aws:kms:eu-west-1:1:key/abc"');
  });

  it('references a SAS token by variable and never writes a credential', () => {
    const env = {
      SQLIB_SQLITE_REPLICA_URL: 'abs://acct@c/prod',
      SQLIB_SQLITE_REPLICA_AZURE_SAS: 'sv=2024&sig=SECRET-SIG',
      LITESTREAM_AZURE_ACCOUNT_KEY: 'SECRET-KEY',
      AWS_SECRET_ACCESS_KEY: 'SECRET-AWS',
    };
    const yaml = buildLitestreamConfig(databases, readReplicaSettings(env)!);
    expect(yaml).toContain('      url: "abs://acct@c/prod/library"');
    expect(yaml).toContain('      sas-token: "${SQLIB_SQLITE_REPLICA_AZURE_SAS}"');
    expect(yaml).not.toMatch(/SECRET/);
  });

  it('refuses a configuration with no SQLite file', () => {
    expect(() => buildLitestreamConfig([], readReplicaSettings({ SQLIB_SQLITE_REPLICA_URL: 's3://b/p' })!)).toThrow(/uses no SQLite file/);
  });

  it('refuses a value Litestream would expand as a variable', () => {
    expect(() =>
      buildLitestreamConfig([{ name: 'library', path: '/data/$HOME/library.sqlite' }], readReplicaSettings({ SQLIB_SQLITE_REPLICA_URL: 's3://b/p' })!)
    ).toThrow(/contains "\$"/);
  });
});
